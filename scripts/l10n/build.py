#!/usr/bin/env python3
"""Builds Resources/<lang>.lproj/Localizable.strings for every language.

Each UI string (l10n/keys.json) is translated, in order of preference, by:
  1. l10n/<lang>.json — the app's own translations (its sentences, and any
     Blender term this app uses in another sense);
  2. Blender's own catalog for that language (the bpy this app ships), so a
     Blender name reads exactly as it does in Blender in that language —
     operator context first, as Blender's menus use it.
Strings neither knows stay English, as Blender leaves an untranslated one.
Writes l10n/missing/<lang>.json with what is left."""
import json, os, re, struct, sys, glob

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
# app language (Apple code) -> Blender's catalog
LANGUAGES = {
    'zh-Hans': 'zh_HANS', 'zh-Hant': 'zh_HANT', 'ja': 'ja', 'ko': 'ko',
    'es': 'es', 'fr': 'fr', 'de': 'de', 'ru': 'ru',
}
CATALOGS = [
    *glob.glob('/Volumes/D/OfflinAi/app_packages/site-packages/bpy/*/datafiles/locale'),
    *glob.glob('/Applications/Blender.app/Contents/Resources/*/datafiles/locale'),
]
CONTEXTS = ['Operator', '*', 'ID', 'Mesh', 'Object']

def load_mo(path):
    b = open(path, 'rb').read()
    _, _, n, oo, to = struct.unpack('<IIIII', b[:20])
    out = {}
    for i in range(n):
        ol, op = struct.unpack('<II', b[oo + 8 * i:oo + 8 * i + 8])
        tl, tp = struct.unpack('<II', b[to + 8 * i:to + 8 * i + 8])
        k, v = b[op:op + ol].decode('utf8'), b[tp:tp + tl].decode('utf8')
        if k and v:
            ctx, _, msg = k.rpartition('\x04')
            out.setdefault(msg, {})[ctx or '*'] = v
    return out

def blender(cat, key):
    def one(k):
        found = cat.get(k)
        if not found:
            return None
        for c in CONTEXTS:
            if c in found:
                return found[c]
        return next(iter(found.values()))
    if (t := one(key)):
        return t
    for suffix in ('…', '...', ':'):
        if key.endswith(suffix) and (t := one(key[:-len(suffix)].rstrip())):
            return t + suffix
    return None

def escape(s):
    return s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')

def main():
    keys = json.load(open(os.path.join(ROOT, 'l10n', 'keys.json')))
    os.makedirs(os.path.join(ROOT, 'l10n', 'missing'), exist_ok=True)
    for lang, code in LANGUAGES.items():
        mo = next((os.path.join(c, code, 'LC_MESSAGES', 'blender.mo') for c in CATALOGS
                   if os.path.exists(os.path.join(c, code, 'LC_MESSAGES', 'blender.mo'))), None)
        cat = load_mo(mo) if mo else {}
        own_path = os.path.join(ROOT, 'l10n', f'{lang}.json')
        own = json.load(open(own_path)) if os.path.exists(own_path) else {}
        table, missing = {}, []
        for k in keys:
            t = own.get(k) or blender(cat, k)
            if t and t != k:
                table[k] = t
            elif not t:
                missing.append(k)
        for k, t in own.items():          # app translations of keys not found by extract
            table.setdefault(k, t)
        out = os.path.join(ROOT, 'Resources', 'Localization', f'{lang}.lproj')
        os.makedirs(out, exist_ok=True)
        with open(os.path.join(out, 'Localizable.strings'), 'w', encoding='utf-8') as f:
            f.write(f'/* Generated by scripts/l10n/build.py: Blender {os.path.basename(os.path.dirname(os.path.dirname(mo))) if mo else "-"} + l10n/{lang}.json */\n')
            for k in sorted(table):
                f.write(f'"{escape(k)}" = "{escape(table[k])}";\n')
        json.dump(missing, open(os.path.join(ROOT, 'l10n', 'missing', f'{lang}.json'), 'w'),
                  ensure_ascii=False, indent=1)
        print(f'{lang:8} {len(table):5} translated, {len(missing):4} English')

if __name__ == '__main__':
    main()
